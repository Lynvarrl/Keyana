#Requires -Version 5.1
<#
.SYNOPSIS
    在构建阶段生成 BuildMetadata.g.cs。

.DESCRIPTION
    Build ID、Git 提交与工作区状态都必须在构建时确定一次，编译进程序集：
    这样同一份产物启动多少次都是同一个 Build ID，打包后的 EXE 也不需要
    Git 或额外的文件即可报出自己来自哪次构建。

    本脚本不会让构建失败：源码不在 Git 仓库里、构建机没有装 Git、
    命令超时或返回异常文本，都只会把对应字段降级成 unknown / Unknown。

.PARAMETER OutputPath
    生成的 C# 文件路径，通常位于 obj 下。

.PARAMETER Version
    软件版本号，由 csproj 的 <Version> 传入，脚本不做任何改写。

.PARAMETER Configuration
    构建配置名（Debug / Release），决定 Build Type。

.PARAMETER RepositoryRoot
    仓库根目录，用于执行 git 命令。
#>
param(
    [Parameter(Mandatory)][string]$OutputPath,
    [Parameter(Mandatory)][string]$Version,
    [string]$Configuration = "Debug",
    [string]$RepositoryRoot = ""
)

# 这里刻意不设置 $ErrorActionPreference = "Stop"：Windows PowerShell 5.1 在原生程序
# 往 stderr 写内容时，配合 Stop 可能抛出 NativeCommandError。所有外部调用都自己检查
# 退出码，失败就降级，不需要全局终止。
$ErrorActionPreference = "Continue"

function ConvertTo-CSharpLiteral {
    param([string]$Value)
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

$buildType = if ($Configuration -eq "Release") { "Release" } else { "Development" }
$buildId = Get-Date -Format "yyyyMMdd-HHmmss"
$gitCommit = "unknown"
$gitStatus = "Unknown"

if (-not [string]::IsNullOrWhiteSpace($RepositoryRoot) -and (Test-Path -LiteralPath $RepositoryRoot)) {
    $repositoryRootFull = [System.IO.Path]::GetFullPath($RepositoryRoot)

    # 没有安装 Git 时 Get-Command 返回 $null，直接走降级分支。
    if ($null -ne (Get-Command git -ErrorAction SilentlyContinue)) {
        try {
            $commitOutput = @(& git -C $repositoryRootFull rev-parse --short HEAD 2>$null)
            if ($LASTEXITCODE -eq 0 -and $commitOutput.Count -gt 0) {
                $candidate = ([string]$commitOutput[0]).Trim()
                if ($candidate -match '^[0-9a-fA-F]{4,64}$') {
                    $gitCommit = $candidate.ToLowerInvariant()
                }
            }
        }
        catch {
            $gitCommit = "unknown"
        }

        # 拿不到提交哈希就不必再问工作区状态：HEAD 不存在时 git status 的结果没有意义。
        if ($gitCommit -ne "unknown") {
            try {
                $statusOutput = @(& git -C $repositoryRootFull status --porcelain --untracked-files=normal 2>$null)
                if ($LASTEXITCODE -ne 0) {
                    $gitStatus = "Unknown"
                }
                elseif (@($statusOutput | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }).Count -gt 0) {
                    $gitStatus = "Modified"
                }
                else {
                    $gitStatus = "Clean"
                }
            }
            catch {
                $gitStatus = "Unknown"
            }
        }
    }
}

$outputFullPath = [System.IO.Path]::GetFullPath($OutputPath)
$outputDirectory = [System.IO.Path]::GetDirectoryName($outputFullPath)
if (-not [string]::IsNullOrWhiteSpace($outputDirectory)) {
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
}

# 文件名固定为 BuildMetadata.g.cs；带 <auto-generated> 头，避免被代码分析当成手写代码。
# 值都已用 ConvertTo-CSharpLiteral 转义，版本号里出现预发布后缀（1.4.0-alpha.1）也能正确落进字符串。
$content = @"
// <auto-generated>
// 由 scripts/build-info.ps1 在构建时生成，请勿手动修改。
// 生成时间：$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz')
// </auto-generated>

namespace Keyana.App;

internal static class BuildMetadata
{
    public const string Version = "$(ConvertTo-CSharpLiteral $Version)";
    public const string BuildId = "$buildId";
    public const string GitCommit = "$gitCommit";
    public const string GitStatus = "$gitStatus";
    public const string BuildType = "$buildType";
}
"@

# 统一成 CRLF：仓库里其他 .cs 都是 CRLF，生成文件也保持一致，避免某些编辑器显示异常。
$content = $content -replace "(?<!\r)\n", "`r`n"

# 带 BOM 的 UTF-8：Windows PowerShell 与旧版工具链读中文注释都不会乱码。
[System.IO.File]::WriteAllText($outputFullPath, $content, (New-Object System.Text.UTF8Encoding($true)))

Write-Host "build-info: $buildId / $buildType / $gitCommit / $gitStatus"
